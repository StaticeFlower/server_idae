-- รันไฟล์นี้ใน Supabase Dashboard -> SQL Editor (ครั้งเดียว)
-- ตรงกับ ERD: USER 1 --- * IDEA

create table if not exists public.users (
  id            uuid primary key default gen_random_uuid(),
  name          text not null,
  email         text not null,
  password_hash text not null,
  created_at    timestamptz not null default now(),
  constraint users_email_key unique (email)
);

create table if not exists public.ideas (
  id          bigint generated by default as identity primary key,
  seller_id   uuid not null references public.users (id) on delete restrict,
  title       text not null,
  summary     text not null,
  full_detail text not null,
  price       integer not null default 0 check (price >= 0),
  created_at  timestamptz not null default now()
);

create index if not exists idx_ideas_seller_id  on public.ideas (seller_id);
create index if not exists idx_ideas_created_at on public.ideas (created_at desc);

-- สำคัญ: Supabase เปิดตารางใน schema public ให้เรียกผ่าน REST API (PostgREST) ได้
-- เปิด RLS โดยไม่สร้าง policy = คนนอกที่ถือ anon key อ่าน/เขียนตารางนี้ไม่ได้
-- (ตาราง users มี password_hash จึงห้ามปล่อยเปิด)
-- API ฝั่ง Go เชื่อมต่อด้วย role postgres ซึ่งข้าม RLS ได้ จึงทำงานได้ตามปกติ
alter table public.users enable row level security;
alter table public.ideas enable row level security;
